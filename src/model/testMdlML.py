import copy
import joblib
import numpy as np
import time
import sys
from sys import getsizeof


#######################################################################################################################
# Function
#######################################################################################################################
def testMdlML(data, setupPar, setupExp):
    ###################################################################################################################
    # MSG IN
    ###################################################################################################################
    print("INFO: Testing Model (ML)")

    ###################################################################################################################
    # Initialisation
    ###################################################################################################################
    # ==============================================================================
    # Parameters
    # ==============================================================================
    mdlName = 'mdl/mdl_' + setupPar['model'] + '_' + setupExp['name'] + '.joblib'

    # ==============================================================================
    # Variables
    # ==============================================================================
    dataPred = {'T': {}}
    dataPred['T']['X'] = copy.deepcopy(data['T']['X'])
    mdl = []

    ###################################################################################################################
    # Pre-Processing
    ###################################################################################################################
    # ==============================================================================
    # Reshape data
    # ==============================================================================
    if np.size(data['T']['X'].shape) == 3:
        data['T']['X'] = data['T']['X'].reshape((data['T']['X'].shape[0], data['T']['X'].shape[1] * data['T']['X'].shape[2]))

    ###################################################################################################################
    # Loading
    ###################################################################################################################
    try:
        mdl = joblib.load(mdlName)
        print("INFO: Model loaded")
    except Exception as e:
        sys.exit("ERROR: Model %s could not be loaded, train it first (%s)" % (mdlName, e))

    ###################################################################################################################
    # Calculation
    ###################################################################################################################
    # ==============================================================================
    # Start timer
    # ==============================================================================
    start = time.time()

    # ==============================================================================
    # Test
    # ==============================================================================
    dataPred['T']['y'] = mdl.predict(data['T']['X'])

    # ==============================================================================
    # End timer
    # ==============================================================================
    ende = time.time()
    testTime = (ende - start)

    ###################################################################################################################
    # Post-Processing
    ###################################################################################################################
    print("INFO: Total inference time (ms): %.2f" % (testTime * 1000))
    print("INFO: Inference time per sample (us): %.2f" % (testTime / data['T']['X'].shape[0] * 1000 * 1000))
    print("INFO: Model size (kB): %.2f" % mdlSize(mdl))

    ###################################################################################################################
    # References
    ###################################################################################################################
    return dataPred

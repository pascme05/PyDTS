from src.general.helpFnc import reshapeMdlData
from src.model.models import buildMdl
from src.model import torchFit as tfit

# ==============================================================================
# External
# ==============================================================================
import time


#######################################################################################################################
# Function
#######################################################################################################################
def testMdlDL(data, setupDat, setupPar, setupMdl, setupExp):
    ###################################################################################################################
    # MSG IN
    ###################################################################################################################
    print("INFO: Test Model (DL)")

    ###################################################################################################################
    # Initialisation
    ###################################################################################################################
    dev = tfit.device(setupExp['gpu'])
    mdlName = tfit.mdlPath(setupPar, setupExp)
    dataPred = {'T': {}}

    ###################################################################################################################
    # Pre-Processing
    ###################################################################################################################
    [data['T']['X'], data['T']['y']] = reshapeMdlData(data['T']['X'], data['T']['y'], setupDat, setupPar, 0)

    ###################################################################################################################
    # Model
    ###################################################################################################################
    out = tfit.outDim(data['T']['y'], setupDat, setupPar)
    activation = 'linear' if setupPar['method'] == 0 else 'sigmoid'
    mdl = buildMdl(setupPar['model'], data['T']['X'].shape[1:], out, activation)
    tfit.load(mdl, mdlName, tfit.meta(data['T']['X'], out, setupPar))
    print("INFO: Model loaded")

    ###################################################################################################################
    # Calculation
    ###################################################################################################################
    start = time.time()
    dataPred['T']['y'] = tfit.predict(mdl, data['T']['X'], max(1, int(setupMdl['batch'])), dev)
    testTime = time.time() - start
    dataPred['T']['X'] = data['T']['X']

    ###################################################################################################################
    # Output
    ###################################################################################################################
    print("INFO: Total inference time (ms): %.2f" % (testTime * 1000))
    print("INFO: Inference time per sample (us): %.2f" % (testTime / data['T']['X'].shape[0] * 1000 * 1000))
    print("INFO: Model size (kB): %.2f" % tfit.mdlSize(mdl))

    return dataPred
